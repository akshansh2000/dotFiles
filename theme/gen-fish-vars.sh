#!/bin/sh
# Generate a fish-native copy of a POSIX-sh variable file.
#
#   gen-fish-vars.sh colors.sh colors.fish
#
# Exists because fish cannot source POSIX sh, so every `NAME=value` file that
# both river/init and config.fish need has to exist twice. Those copies used to
# be kept in step by hand, which is a silent-drift bug waiting to happen: a
# palette edit propagates to waybar/rofi/foot the moment apply-theme.sh runs,
# but a forgotten colors.fish would keep handing stale colours to every new
# shell, with nothing to flag the mismatch. apply-theme.sh calls this now, so
# the .fish files are build artifacts and the .sh files are the only source.
#
# Handled deliberately:
#   - `# --- section ---` comments are carried over, so the output stays as
#     readable as the input; trailing per-line comments are dropped.
#   - values containing spaces are re-quoted (fonts.sh has "Fira Code", which
#     is exactly the case that broke apply-theme.sh's sed args once before).
set -eu

[ $# -eq 2 ] || { echo "usage: $(basename "$0") <input.sh> <output.fish>" >&2; exit 2; }
src=$1
dst=$2
[ -r "$src" ] || { echo "cannot read $src" >&2; exit 1; }

tmp=$(mktemp "$dst.XXXXXX")
trap 'rm -f "$tmp"' EXIT

{
	echo "#!/usr/bin/env fish"
	echo "# GENERATED by ~/.config/theme/gen-fish-vars.sh from $(basename "$src") -"
	echo "# do not edit. Change $(basename "$src") and run apply-theme.sh."
	awk '
		# Section headers only; the sh file header and per-line notes stay put.
		/^# ---/ { print ""; print; printed = 1; next }
		# NAME=value, with an optional trailing comment.
		/^[A-Za-z_][A-Za-z0-9_]*=/ {
			# One blank line after our header, whether the first thing in the
			# file is a section comment (colors.sh) or a bare value (fonts.sh).
			if (!printed) { print ""; printed = 1 }
			eq = index($0, "=")
			name = substr($0, 1, eq - 1)
			val = substr($0, eq + 1)
			sub(/[ \t]+#.*$/, "", val)     # trailing comment
			sub(/[ \t]+$/, "", val)
			gsub(/^"|"$/, "", val)         # sh quoting, re-added below if needed
			if (val ~ /[ \t]/) printf "set -gx %s \"%s\"\n", name, val
			else               printf "set -gx %s %s\n", name, val
		}
	' "$src"
} > "$tmp"

# Same 644 as the other generated files: mktemp makes 0600 and mv keeps it.
chmod 644 "$tmp"
mv "$tmp" "$dst"
trap - EXIT
